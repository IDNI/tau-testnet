"""Native-evidence wave, Bounty 01 stage 1 in rules form (#34/#35).

Companion to tests/test_payout_triggers.py (the mock suite) and
tests/test_payouts_grants_native.py (the stage-3 native file, whose
harness this file reuses). The mock suite computes the payout legs
in Python (a scripted evaluator playing the clause's role). This
file instead seeds the two proportional clause templates shipped in
consensus/payouts.py -- TEMPLATE_PERCENTAGE_ROUTE_CLAUSE (20%) and
TEMPLATE_ROYALTY_5PCT_CLAUSE (5%) -- into the real Tau interpreter
and lets the real engine step them, so the leg amounts asserted
here (20 on a 101 credit, 5 on a 101 execution) are the
interpreter's own outputs, not a Python re-computation.

Why this file exists, stated plainly: the stage-3 native file used
a FIXED leg of 5 for its royalty case because a proportional clause
(o21 = (i1 * 5) / 100) had no green native run in this repo -- the
arithmetic probe that carries the pattern
(tests/test_o9_arithmetic_probe_native.py) is not registered in CI
and skips in the dev VM. These three tests close that gap for the
two templates this PR ships:

  case 1 -- 101 credited to a 20% receive route pays 20 onward and
            leaves 81 with the owner (arrival trigger, real clause);
  case 2 -- a 5% royalty on a gross of 101 pays exactly 5, once
            (manual execution, real clause; replay settles nothing);
  case 2b -- the same royalty in arrival form pays once per
            crediting transaction id: replaying the credit under
            the same id lands the credit but not a second royalty.

Gate: idiom A, as in the stage-3 file. Locally every test skips
(the checked-in tau build targets a different Python than the dev
venv -- the gap documented in the arithmetic probe's docstring);
the native CI job builds the matching module and runs this file.
Fees are the real genesis program's flat fee, charged to each tx's
sender and credited to the proposer; every fee below is measured
off the proposer's balance, never assumed.
"""
