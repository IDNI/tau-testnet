# --- tx builders: the stage-3 native file's, plus the mock trigger
# --- suite's transfer builder ---------------------------------------------

FAR = 9_999_999_999


def _ts(year, month, day, hour=0):
    return int(datetime(year, month, day, hour, tzinfo=timezone.utc).timestamp())


NOW = _ts(2026, 1, 15, 12)
JAN1 = _ts(2026, 1, 1)


def _key(seed: int):
    return seed, G2Basic.SkToPk(seed).hex()


SK_ALICE, ALICE = _key(11111)
SK_BOB, BOB = _key(44444)
SK_CAROL, CAROL = _key(55555)
PROPOSER = "d4" * 48

_TX_SEQ = itertools.count()


def _sign(tx: dict, sk: int) -> dict:
    digest = hashlib.sha256(signing_message_bytes(tx)).digest()
    tx["signature"] = G2Basic.Sign(sk, digest).hex()
    return tx


def install_tx(owner=ALICE, sk=SK_ALICE, seq=0, extra=None, **kw):
    tx = {
        "tx_id": f"payout-install-{next(_TX_SEQ)}",
        "tx_type": "payout_rule_install",
        "sender_pubkey": owner,
        "sequence_number": seq,
        "expiration_time": FAR,
        "expire_at_height": 1000,
        "fee_limit": "100",
        "max_per_execution": kw.get("max_per_execution", 1000),
        "max_per_period": kw.get("max_per_period", 1500),
        "recipients": kw.get("recipients", [BOB, CAROL]),
        "period_kind": kw.get("period_kind", 2),
        "anchor_ts": kw.get("anchor_ts", JAN1),
    }
    tx.update(extra or {})
    return _sign(tx, sk)


def execute_tx(owner=ALICE, executor=CAROL, sk=SK_CAROL, seq=0,
               settlement_id="s1", gross=101, extra=None):
    tx = {
        "tx_id": f"payout-exec-{next(_TX_SEQ)}",
        "tx_type": "payout_execute",
        "sender_pubkey": executor,
        "sequence_number": seq,
        "expiration_time": FAR,
        "expire_at_height": 1000,
        "fee_limit": "100",
        "owner": owner,
        "settlement_id": settlement_id,
        "gross": gross,
    }
    tx.update(extra or {})
    return _sign(tx, sk)


def transfer_tx(to, amount, sk, *, sender, seq=0, tx_id=None):
    tx = {
        "tx_id": tx_id or f"transfer-{next(_TX_SEQ)}",
        "tx_type": "user_tx",
        "sender_pubkey": sender,
        "sequence_number": seq,
        "expiration_time": FAR,
        "expire_at_height": 1000,
        "fee_limit": "100",
        "operations": {"1": [[sender, to, str(amount)]]},
    }
    return _sign(tx, sk)


class Chain:
    """The stage-3 native file's Chain, unchanged: the mock suites'
    snapshot-carried balances with no patches on the Tau path."""

    def __init__(self, balances):
        self.bal = dict(balances)
        self.seq = {}
        self.lts = {}
        self.lm = ConsensusLifecycleManager(active_validators=[ALICE])
        self.last = None

    def block(self, txs, height=20, ts=NOW):
        parent = TauStateSnapshot(
            state_hash="0" * 64,
            tau_bytes=b"always (o0[t]=1).",
            metadata={
                "balances": dict(self.bal),
                "sequence_numbers": dict(self.seq),
                "last_transfer_ts": dict(self.lts),
                "lifecycle_manager": self.lm,
                "consensus_rules_state": "always (o6[t]:bv[16] = i10[t]:bv[16]).",
                "active_consensus_id": "",
            },
        )
        view = ActiveConsensusView(
            target_height=height,
            consensus_rules=parent.metadata["consensus_rules_state"],
            active_validators=[bytes.fromhex(ALICE)],
            mechanism_specific_metadata={"poa": True},
        )
        blk = Block.create(
            block_number=height, previous_hash="00" * 32, transactions=txs,
            proposer_pubkey=PROPOSER, timestamp=ts,
        )
        engine = TauConsensusEngine()
        result = engine.apply_block(view, blk, parent)
        meta = result.next_snapshot.metadata
        self.bal = dict(meta["balances"])
        self.seq = dict(meta["sequence_numbers"])
        self.lts = dict(meta["last_transfer_ts"])
        self.lm = meta["lifecycle_manager"]
        self.last = result
        return result

    @property
    def payout_book(self):
        return self.lm.payout_rules

    def accepted(self, tx):
        return tx["tx_id"] in self.last.accepted_tx_ids

    def receipt(self, tx):
        for outcome in self.last.outcomes:
            if outcome.tx_id == tx["tx_id"]:
                return {"logs": outcome.receipt_logs, "reason": outcome.reason}
        raise KeyError(tx["tx_id"])

    def payout_events(self):
        return self.last.next_snapshot.metadata.get("payout_events", [])


def _install_payout_clause(ch: Chain, owner: str, clause: str):
    """Register the owner's payout clause the two ways the
    production state holds it (stage-3 native file, resolution #5):
    the rule_offers registry entry, written exactly as
    submit_decision writes it, and the clause unit seeded into the
    interpreter's spec through tau_manager with the rules update
    on."""
    ch.lm.rule_offers.accepted_clauses[(owner, PAYOUT_STREAM_INDEX)] = clause
    tau_manager.communicate_with_tau(
        rule_text=clause, target_output_stream_index=0,
        apply_rules_update=True, source="native-payout-clause",
    )


# --- the proportional templates, stepped by the real interpreter -----------


def test_route_20pct_on_101_arrival_native():
    """Maintainer case 1 (#34/#35): BOB's receive route is the
    shipped 20% template itself, stepped by the real interpreter.
    A 101 credit to BOB forwards exactly 20 to the declared
    recipient and leaves 81 with BOB; the only fee in the block is
    the crediting transfer's own (measured off the proposer)."""
    ch = Chain({ALICE: 10_000, BOB: 1_000, CAROL: 0, PROPOSER: 0})
    _install_payout_clause(ch, BOB, TEMPLATE_PERCENTAGE_ROUTE_CLAUSE)
    install = install_tx(owner=BOB, sk=SK_BOB, recipients=[CAROL],
                         extra={"on_arrival": True})
    ch.block([install], height=20, ts=NOW)
    assert ch.accepted(install), ch.receipt(install)
    assert ch.payout_book.get(BOB) is not None

    before = dict(ch.bal)
    tx = transfer_tx(BOB, 101, SK_ALICE, sender=ALICE, seq=0,
                     tx_id="route-credit-101")
    ch.block([tx], height=21, ts=NOW)
    assert ch.accepted(tx), ch.receipt(tx)
    fee = ch.bal[PROPOSER] - before[PROPOSER]
    assert fee > 0
    assert ch.bal[CAROL] - before[CAROL] == 20
    assert ch.bal[BOB] - before[BOB] == 101 - 20
    assert ch.bal[ALICE] - before[ALICE] == -101 - fee
    sid = arrival_settlement_id("route-credit-101")
    assert ch.payout_events() == [(sid, "executed")]
    state = ch.payout_book.get(BOB)
    assert state.settlements == [sid]
    assert state.spent_in_period == 20


def test_royalty_5pct_on_101_execute_native():
    """Maintainer case 2 (#35), execution form: ALICE's clause is
    the shipped 5% royalty template itself. Executing it over a
    gross of 101 pays the declared recipient exactly 5 -- the real
    interpreter's (101 * 5) / 100, floored -- and a replay under
    the same settlement id settles nothing."""
    ch = Chain({ALICE: 10_000, BOB: 0, CAROL: 1_000, PROPOSER: 0})
    _install_payout_clause(ch, ALICE, TEMPLATE_ROYALTY_5PCT_CLAUSE)
    install = install_tx()
    ch.block([install], height=20, ts=NOW)
    assert ch.accepted(install), ch.receipt(install)
    install_fee = ch.bal[PROPOSER]
    assert install_fee > 0
    assert ch.bal[ALICE] == 10_000 - install_fee

    ex = execute_tx(settlement_id="royalty-101", gross=101)
    ch.block([ex], height=21, ts=NOW)
    assert ch.accepted(ex), ch.receipt(ex)
    assert ch.bal[BOB] == 5
    assert ch.bal[ALICE] == 10_000 - install_fee - 5
    exec_fee = ch.bal[PROPOSER] - install_fee
    assert exec_fee == install_fee
    assert ch.bal[CAROL] == 1_000 - exec_fee
    assert ch.payout_events() == [("royalty-101", "executed")]
    state = ch.payout_book.get(ALICE)
    assert state.settlements == ["royalty-101"]
    assert state.spent_in_period == 5

    replay = execute_tx(seq=1, settlement_id="royalty-101", gross=101)
    ch.block([replay], height=22, ts=NOW)
    assert not ch.accepted(replay)
    assert "already settled" in " ".join(ch.receipt(replay)["logs"])
    assert ch.bal[BOB] == 5
    assert ch.bal[ALICE] == 10_000 - install_fee - 5
    assert ch.payout_events() == []
    assert ch.payout_book.get(ALICE).settlements == ["royalty-101"]


def test_royalty_5pct_arrival_pays_once_native():
    """Maintainer case 2, arrival form: BOB's route is the shipped
    5% royalty template. A 101 credit pays CAROL exactly 5 under
    the crediting transaction's settlement id; replaying the same
    credit under the same id lands the credit again but pays no
    second royalty."""
    ch = Chain({ALICE: 10_000, BOB: 0, CAROL: 0, PROPOSER: 0})
    _install_payout_clause(ch, BOB, TEMPLATE_ROYALTY_5PCT_CLAUSE)
    install = install_tx(owner=BOB, sk=SK_BOB, recipients=[CAROL],
                         extra={"on_arrival": True})
    ch.block([install], height=20, ts=NOW)
    assert ch.accepted(install), ch.receipt(install)

    tx = transfer_tx(BOB, 101, SK_ALICE, sender=ALICE, seq=0,
                     tx_id="credit-101")
    ch.block([tx], height=21, ts=NOW)
    assert ch.accepted(tx), ch.receipt(tx)
    assert ch.bal[CAROL] == 5
    assert ch.bal[BOB] == 101 - 5

    replay = transfer_tx(BOB, 101, SK_ALICE, sender=ALICE, seq=1,
                         tx_id="credit-101")
    ch.block([replay], height=22, ts=NOW)
    assert ch.accepted(replay), ch.receipt(replay)
    assert ch.bal[CAROL] == 5
    assert ch.bal[BOB] == 101 - 5 + 101
    assert ch.payout_book.get(BOB).settlements == [
        arrival_settlement_id("credit-101")]
